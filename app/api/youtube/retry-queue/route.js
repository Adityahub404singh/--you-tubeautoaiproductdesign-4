import { NextResponse } from "next/server";
import { readdir, readFile, unlink } from "fs/promises";
import { existsSync, statSync, createReadStream } from "fs";
import path from "path";

const QUEUE_DIR = path.join(process.cwd(), "storage", "ready_to_upload");

async function uploadVideoMemorySafe(videoPath, metadata, token) {
  const fileSize = statSync(videoPath).size;
  
  const initRes = await fetch(
    "https://www.googleapis.com/upload/youtube/v3/videos?uploadType=resumable&part=snippet,status",
    {
      method: "POST",
      headers: {
        Authorization: `Bearer ${token}`,
        "Content-Type": "application/json",
        "X-Upload-Content-Type": "video/mp4",
        "X-Upload-Content-Length": fileSize.toString(),
      },
      body: JSON.stringify({
        snippet: {
          title: (metadata?.title || "Video").slice(0, 100),
          description: (metadata?.description || "Generated by YouTubeAuto.ai") + "\n\n#viral #trending",
          tags: Array.isArray(metadata?.tags) ? metadata.tags.slice(0, 15) : [],
          categoryId: metadata?.categoryId || "22"
        },
        status: { privacyStatus: metadata?.privacyStatus || "public", selfDeclaredMadeForKids: false },
      }),
    }
  );

  if (!initRes.ok) {
    const err = await initRes.json().catch(() => ({}));
    if (err?.error?.errors?.[0]?.reason === "uploadLimitExceeded") throw new Error("QUOTA_EXCEEDED");
    throw new Error(err?.error?.message || "Init failed: " + initRes.status);
  }

  const uploadUrl = initRes.headers.get("location");
  if (!uploadUrl) throw new Error("No upload URL returned from YouTube");

  // STREAM-BASED UPLOAD (Memory Safe - No RAM Overload)
  const fileStream = createReadStream(videoPath, { highWaterMark: 1 * 1024 * 1024 });
  const iterator = fileStream[Symbol.asyncIterator]();
  const stream = new ReadableStream({
    async pull(controller) {
      const { value, done } = await iterator.next();
      if (done) { controller.close(); } else { controller.enqueue(value); }
    }
  });

  const uploadRes = await fetch(uploadUrl, {
    method: "PUT",
    headers: { "Content-Type": "video/mp4", "Content-Length": fileSize.toString() },
    body: stream,
    duplex: 'half'
  });

  if (!uploadRes.ok) {
    const errText = await uploadRes.text();
    throw new Error("Stream upload failed: " + errText);
  }

  const uploadedData = await uploadRes.json();
  return uploadedData.id;
}

export async function GET() {
  try {
    if (!existsSync(QUEUE_DIR)) return NextResponse.json({ queued: 0, items: [] });
    const files = (await readdir(QUEUE_DIR)).filter(f => f.endsWith(".json"));
    const items = [];
    for (const f of files) {
      try {
        const d = JSON.parse(await readFile(path.join(QUEUE_DIR, f), "utf8"));
        items.push({ file: f, title: d.title, queuedAt: d.queuedAt, videoUrl: d.videoUrl });
      } catch {}
    }
    return NextResponse.json({ queued: items.length, items });
  } catch (e) {
    return NextResponse.json({ error: e.message }, { status: 500 });
  }
}

export async function POST(req) {
  try {
    const { processAll = false, accessToken } = await req.json().catch(() => ({}));
    if (!existsSync(QUEUE_DIR)) return NextResponse.json({ processed: 0, message: "Queue empty" });

    const files = (await readdir(QUEUE_DIR)).filter(f => f.endsWith(".json"));
    if (files.length === 0) return NextResponse.json({ processed: 0, message: "Queue empty" });

    const token = accessToken || process.env.YOUTUBE_ACCESS_TOKEN;
    if (!token) return NextResponse.json({ error: "No YouTube token available. Connect YouTube first." }, { status: 401 });

    const toProcess = processAll ? files : files.slice(0, 1);
    const results = [];

    for (const file of toProcess) {
      const jsonPath = path.join(QUEUE_DIR, file);
      try {
        const queuedData = JSON.parse(await readFile(jsonPath, "utf8"));
        const fileName = queuedData.videoUrl.split("/").pop();
        const videoPath = path.join(process.cwd(), "storage", "videos", fileName);

        if (!existsSync(videoPath)) {
          await unlink(jsonPath);
          results.push({ file, status: "skipped", reason: "video file missing" });
          continue;
        }

        console.log(`?? Retrying upload for: ${queuedData.title}`);
        const videoId = await uploadVideoMemorySafe(videoPath, queuedData, token);
        await unlink(jsonPath);
        results.push({ file, status: "uploaded", videoId, url: `https://youtube.com/watch?v=${videoId}` });
        console.log(`? Retry Successful! Video ID: ${videoId}`);
        
        if (toProcess.length > 1) await new Promise(r => setTimeout(r, 3000));
      } catch (e) {
        if (e.message === "QUOTA_EXCEEDED") {
          results.push({ file, status: "quota_exceeded" });
          break;
        }
        results.push({ file, status: "failed", reason: e.message });
      }
    }

    return NextResponse.json({ success: true, processed: results.length, results });

  } catch(error: any) {
    console.error("Retry Queue Error:", error.message);
    return NextResponse.json({ error: error.message }, { status: 500 });
  }
}

